class I18NManager:
    """Manages active language, system detection, and string translation."""
    
    _instance = None

    def __init__(self):
        self._current_lang = "ru"
        self._configured_lang = "auto"
        self._current_lang = self.detect_system_language()

    @classmethod
    def instance(cls) -> "I18NManager":
        if cls._instance is None:
            cls._instance = cls()
        return cls._instance

    def detect_system_language(self) -> str:
        """Determines best matching supported language from Windows / QLocale."""
        loc = QLocale.system()
        # Check standard ISO name prefix (e.g. 'ru', 'en', 'de', 'fr', 'es', 'zh', 'ja')
        lang_code = loc.name().split('_')[0].lower()
        if lang_code in TRANSLATIONS:
            return lang_code
        # Fallback to English if not Russian/supported
        return "en"

    def set_language(self, lang: str):
        self._configured_lang = lang
        if lang == "auto":
            self._current_lang = self.detect_system_language()
        elif lang in TRANSLATIONS:
            self._current_lang = lang
        else:
            self._current_lang = "en"

    def get_configured_language(self) -> str:
        return self._configured_lang

    def get_current_language(self) -> str:
        return self._current_lang

    def tr(self, key: str, **kwargs) -> str:
        """Translates a key into current language with fallback to Russian and English."""
        trans = TRANSLATIONS.get(self._current_lang, {})
        val = trans.get(key)
        if val is None:
            val = TRANSLATIONS.get("en", {}).get(key)
        if val is None:
            val = TRANSLATIONS.get("ru", {}).get(key, key)
        if kwargs:
            try:
                return val.format(**kwargs)
            except Exception:
                return val
        return val


def tr(key: str, **kwargs) -> str:
    """Convenience global translation function."""
    return I18NManager.instance().tr(key, **kwargs)
